# Build locally from reviewed source using installed Microsoft C++ Build Tools.
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

if ($env:OS -ne 'Windows_NT') { throw 'This adapter must be built with MSVC on Windows x64.' }
$repo = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$build = Join-Path $repo 'build/mpay_browser_adapter'
New-Item -ItemType Directory -Force -Path $build | Out-Null

# Locate an already installed toolchain. No installer or network access is used.
if (!(Get-Command cl.exe -ErrorAction SilentlyContinue) -or $env:VSCMD_ARG_TGT_ARCH -ne 'x64') {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio/Installer/vswhere.exe'
    if (!(Test-Path -LiteralPath $vswhere)) {
        throw 'Install the Microsoft C++ x64 Build Tools, then run this script in an x64 Developer PowerShell.'
    }
    $vs = (& $vswhere -latest -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath | Select-Object -First 1)
    if (!$vs) { throw 'No installed Microsoft C++ x64 toolchain was found.' }
    $vcvars = Join-Path $vs 'VC/Auxiliary/Build/vcvarsall.bat'
    $environment = & $env:ComSpec /d /s /c "`"`"$vcvars`" x64 >nul && set`""
    if ($LASTEXITCODE -ne 0) { throw 'vcvarsall.bat x64 failed.' }
    foreach ($line in $environment) {
        if ($line -match '^([^=]+)=(.*)$') { [Environment]::SetEnvironmentVariable($Matches[1], $Matches[2], 'Process') }
    }
}
$cl = (Get-Command cl.exe -ErrorAction Stop).Source
$dumpbin = (Get-Command dumpbin.exe -ErrorAction Stop).Source
$source = Join-Path $PSScriptRoot 'adapter.cpp'
$definition = Join-Path $PSScriptRoot 'adapter.def'
$dll = Join-Path $build 'webview_support_helper.dll'
$object = Join-Path $build 'adapter.obj'
$importLibrary = Join-Path $build 'webview_support_helper.lib'

& $cl /nologo /std:c++17 /permissive- /utf-8 /W4 /WX /EHsc /O2 /MT /guard:cf `
    /DWIN32_LEAN_AND_MEAN /DNOMINMAX /LD "/Fo$object" "/Fe$dll" $source `
    /link "/DEF:$definition" "/IMPLIB:$importLibrary" /MACHINE:X64 /DYNAMICBASE `
    /HIGHENTROPYVA /NXCOMPAT /GUARD:CF /INCREMENTAL:NO user32.lib
if ($LASTEXITCODE -ne 0) { throw "MSVC adapter build failed (exit $LASTEXITCODE)." }

$headers = (& $dumpbin /nologo /headers $dll) -join "`n"
if ($LASTEXITCODE -ne 0 -or $headers -notmatch '(?im)^\s*8664 machine') { throw 'Built adapter is not an x64 PE DLL.' }
$exportText = (& $dumpbin /nologo /exports $dll) -join "`n"
if ($LASTEXITCODE -ne 0) { throw 'Cannot inspect the adapter exports.' }
$expected = @(Get-Content -LiteralPath $definition | Where-Object { $_ -match '^\s+[A-Za-z_][A-Za-z_0-9]*\s*$' } | ForEach-Object { $_.Trim() } | Sort-Object)
$actual = @([regex]::Matches($exportText, '(?m)^\s*\d+\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]+\s+(\w+)\s*$') | ForEach-Object { $_.Groups[1].Value } | Sort-Object)
if ($expected.Count -ne 16 -or $actual.Count -ne 16 -or @(Compare-Object $expected $actual).Count) {
    throw "Adapter exports do not match the exact 11 SDK + 5 host symbols.`n$exportText"
}
$imports = (& $dumpbin /nologo /imports $dll) -join "`n"
if ($LASTEXITCODE -ne 0) { throw 'Cannot inspect the adapter imports.' }
if ($imports -match '(?i)\b(?:mshtml|ieframe|ole32|oleaut32|webview2loader|libcef|Qt6WebEngineCore|VCRUNTIME\d+(?:_\d+)?|MSVCP\d+(?:_\d+)?)\.dll\b') {
    throw 'Unexpected embedded-renderer, COM, or dynamically linked MSVC runtime dependency.'
}

# Publish the DLL and its generated source-build manifest only after inspection.
$artifact = Join-Path $repo 'assets/webview_support_helper.dll'
$manifest = Join-Path $repo 'src/mpay_browser_build.py'
Copy-Item -LiteralPath $dll -Destination $artifact -Force
$sha256 = (Get-FileHash -LiteralPath $artifact -Algorithm SHA256).Hash.ToLowerInvariant()
$content = "# Generated by native/mpay_browser_adapter/build.ps1; do not hand-edit.`nMPAY_BROWSER_HELPER_SHA256 = `"$sha256`"`n"
[IO.File]::WriteAllText($manifest, $content, [Text.UTF8Encoding]::new($false))
Write-Host "Built Windows x64 adapter; verified 11 SDK and 5 host exports. SHA-256: $sha256"
Write-Host 'This is a build/PE inspection, not validation against the live vendor SDK or a vendor account.'
